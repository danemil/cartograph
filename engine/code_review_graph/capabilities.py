def _flag_entry(action: argparse.Action) -> Optional[dict[str, Any]]:
    """Describe one argparse action, or None if it should not be listed."""
    if action.dest in ("help", "==SUPPRESS=="):
        return None
    entry: dict[str, Any] = {"name": action.dest}
    if action.option_strings:
        entry["flag"] = max(action.option_strings, key=len)
    else:
        entry["positional"] = True
        entry["required"] = True
    if action.choices:
        entry["choices"] = list(action.choices)
    if action.default not in (None, False) and not action.option_strings:
        entry["default"] = action.default
    elif action.default not in (None, False):
        entry["default"] = action.default
    if action.help and action.help != argparse.SUPPRESS:
        entry["help"] = action.help
    return entry


def _command_entry(
    name: str,
    parser: argparse.ArgumentParser,
    *,
    full: bool,
    fallback_help: str = "",
) -> dict[str, Any]:
    # `when` prefers the curated decision-phrased line, then the `help=` given
    # to add_parser (which argparse keeps on the parent action, not here), then
    # the parser's own description.
    when = (
        _WHEN.get(name)
        or fallback_help
        or (parser.description or "")
    ).strip()
    entry: dict[str, Any] = {
        "name": name,
        "when": when,
        "example": _EXAMPLES.get(name, f"carto {name}"),
    }
    if not full:
        return entry
    args: list[dict[str, Any]] = []
    flags: list[dict[str, Any]] = []
    for action in parser._actions:  # noqa: SLF001 — argparse exposes no public API
        described = _flag_entry(action)
        if described is None:
            continue
        (args if described.get("positional") else flags).append(described)
    entry["arguments"] = args
    entry["flags"] = flags
    return entry


def build_catalogue(
    parser: argparse.ArgumentParser,
    *,
    command: Optional[str] = None,
    version: str = "unknown",
) -> dict[str, Any]:
    """Introspect the live parser into a catalogue.

    Without ``command`` this is the compact listing: every agent-facing command
    with when-to-use and an example, and nothing else. That keeps the default
    response small enough for an agent to read speculatively.

    With ``command`` it returns full argument and flag detail for that one
    command — the drill-down an agent does once it knows what it wants.
    """
    subparsers = next(
        (a for a in parser._actions if isinstance(a, argparse._SubParsersAction)),  # noqa: SLF001
        None,
    )
    catalogue: dict[str, Any] = {
        "contract": "capability-v1",
        "envelope_schema": 1,
        "tool": "cartograph",
        "binary": "carto",
        "version": version,
        "conventions": {
            "format": "Every command accepts --format json|text. Agents should always pass json.",
            "budget": "--max-tokens bounds the response. Truncation is semantic, never a byte cut.",
            "exit_codes": {
                "0": "success — an empty result is success, not an error",
                "1": "usage error — the call was malformed",
                "2": "precondition unmet — read error.remediation and act on it, then retry",
                "3": "internal error",
            },
            "paging": "List results carry a page block. At most one collection per response pages.",
        },
    }
    if subparsers is None:
        catalogue["commands"] = []
        return catalogue

    if command:
        sub = subparsers.choices.get(command)
        if sub is None:
            known = sorted(c for c in subparsers.choices if c not in _NOT_AGENT_FACING)
            raise KeyError(
                f"unknown command {command!r}; agent-facing commands are: {', '.join(known)}"
            )
        catalogue["commands"] = [_command_entry(command, sub, full=True)]
        return catalogue

    # argparse stores the `help=` text from add_parser on the parent action,
    # not on the subparser, so it has to be recovered separately.
    help_for = {
        a.dest: (a.help or "")
        for a in getattr(subparsers, "_choices_actions", [])
    }

    seen: set[int] = set()
    commands = []
    for name, sub in subparsers.choices.items():
        if name in _NOT_AGENT_FACING:
            continue
        # argparse registers aliases as separate keys pointing at one parser;
        # listing the same command twice would just cost the agent context.
        if id(sub) in seen:
            continue
        seen.add(id(sub))
        commands.append(
            _command_entry(name, sub, full=False, fallback_help=help_for.get(name, ""))
        )
    catalogue["commands"] = sorted(commands, key=lambda c: c["name"])
    catalogue["detail"] = "For full flags on one command: carto capabilities --command <name>"
    return catalogue
