"""`carto capabilities` — the machine-readable command catalogue.

This is the contract's recovery path. Skills are authoritative for *how* to work
(they teach workflows), but a skill can be skipped, stale, or absent on a host
we did not anticipate. When that happens the agent still needs to discover the
surface, and `carto capabilities` is how: a bounded JSON catalogue of every
command, its arguments, and a runnable example.

It also does load-bearing work for token economy. Because the reference detail
lives here, skill bodies do not have to carry it — they can describe four or
five commands for a workflow and point at this for the long tail.

**The catalogue is generated by introspecting the live argparse parser**, never
hand-maintained. A hand-written catalogue drifts from the CLI the moment someone
adds a flag, and a catalogue that lies is worse than none — the agent would
confidently invoke commands that do not exist. This is the same class of bug as
the `query` choices list that hid eight patterns for who knows how long.
"""

from __future__ import annotations

import argparse
from typing import Any, Optional

#: Commands that exist for humans or installation, not for agents. Listing them
#: spends an agent's context on things it should never call.
_NOT_AGENT_FACING = frozenset({
    "install", "init", "uninstall", "serve", "mcp", "daemon", "watch", "eval",
    "register", "unregister", "capabilities",
})

#: A runnable example per command. Examples do more than illustrate — they are
#: the fastest way for a model to infer argument order and shape.
